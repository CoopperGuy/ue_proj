"""Register the three monster roles through sequential native Unreal MCP calls.

Never execute this script inside ProgrammaticToolset: its outer Undo transaction
conflicts with the native DataTable import implementation. No uasset file is read
or written directly. Existing table rows are checked before each save.
"""
import copy
from datetime import datetime, timezone
import json
from pathlib import Path

from native_mcp_client import UnrealMCP


DATA = Path(__file__).resolve().parents[2] / "docs" / "Monsters"
ASSETS = "editor_toolset.toolsets.asset.AssetTools"
DT = "editor_toolset.toolsets.data_table.DataTableTools"
OBJECTS = "editor_toolset.toolsets.object.ObjectTools"
BLUEPRINTS = "editor_toolset.toolsets.blueprint.BlueprintTools"
TAGS = "GameplayTagsToolset.GameplayTagsToolset"


def table_ref(name):
    return {"refPath": f"/Game/Datatable/{name}.{name}"}


def asset_ref(path):
    return {"refPath": path + "." + path.rsplit("/", 1)[1]}


def rows(client, name):
    ref = table_ref(name)
    names = client.call(DT, "list_rows", {"data_table": ref})
    return json.loads(client.call(DT, "get_rows", {"data_table": ref, "row_names": names}))


def save(client, paths):
    if not client.call(ASSETS, "save_assets", {"asset_paths": paths}):
        raise RuntimeError("Save failed: " + repr(paths))
    for path in paths:
        if client.call(ASSETS, "is_dirty", {"asset_path": path}):
            raise RuntimeError("Asset remains dirty: " + path)


def write_json(name, value):
    (DATA / name).write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def verify_subset(actual, expected, path=""):
    if isinstance(expected, dict):
        for key, value in expected.items():
            verify_subset(actual[key], value, path + "." + key)
    elif isinstance(expected, list):
        if len(actual) != len(expected):
            raise RuntimeError("Length mismatch: " + path)
        for index, value in enumerate(expected):
            verify_subset(actual[index], value, f"{path}[{index}]")
    elif isinstance(expected, float):
        if abs(actual - expected) > 0.0001:
            raise RuntimeError(f"Value mismatch: {path}: {actual!r} != {expected!r}")
    elif actual != expected:
        raise RuntimeError(f"Value mismatch: {path}: {actual!r} != {expected!r}")


def write_table(client, name, desired, before):
    missing = [key for key in desired if key not in before]
    if missing:
        client.call(DT, "add_rows", {"data_table": table_ref(name), "row_names": missing})
    client.call(DT, "set_rows", {"data_table": table_ref(name), "values": json.dumps(desired)})
    after = rows(client, name)
    for key, row in before.items():
        if key not in desired and after.get(key) != row:
            raise RuntimeError(f"Existing row changed; not saving: {name}.{key}")
        if key in desired:
            for field, value in row.items():
                if field not in desired[key] and after[key].get(field) != value:
                    raise RuntimeError(f"Existing field changed; not saving: {name}.{key}.{field}")
    for key, expected in desired.items():
        # FText exports contain localization keys generated by the editor.
        comparable = {k: v for k, v in expected.items() if k not in ("skillName", "description")}
        verify_subset(after[key], comparable, name + "." + key)
    save(client, ["/Game/Datatable/" + name])
    print(json.dumps({"saved": name, "updated_rows": list(desired)}, ensure_ascii=False), flush=True)
    return after


def main():
    plan = json.loads((DATA / "pack.json").read_text(encoding="utf-8"))
    client = UnrealMCP()
    discovery = client.request("tools/call", {"name": "list_toolsets", "arguments": {}})
    if discovery.get("isError"):
        raise RuntimeError("Unreal toolset discovery failed")
    for toolset in (ASSETS, DT, OBJECTS, BLUEPRINTS, TAGS, "EditorToolset.EditorAppToolset"):
        client.tool("describe_toolset", {"toolset_name": toolset})
    if client.call("EditorToolset.EditorAppToolset", "IsPIERunning", {}):
        raise RuntimeError("Stop PIE before registering monsters")

    table_names = ("DT_GASSkillData", "DT_DiaMonsterTable", "DT_SpawnGroupTable")
    before = {name: rows(client, name) for name in table_names}
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    write_json("tables-before-" + stamp + ".json", before)
    for table, desired, field in ((table_names[0], plan["skills"], "skillId"),
                                  (table_names[1], plan["monsters"], "monsterId")):
        occupied = {row[field] for key, row in before[table].items() if key not in desired}
        for key, row in desired.items():
            if row[field] in occupied:
                raise RuntimeError("ID conflict: " + key)
            if key in before[table] and before[table][key][field] not in (0, "None", row[field]):
                raise RuntimeError("Row name conflict: " + key)

    asset_paths = []
    for asset in plan.get("additionalAssets", []):
        if not client.call(ASSETS, "exists", {"path": asset["path"]}):
            if not client.call(ASSETS, "duplicate", {"path": asset["source"], "new_path": asset["path"]}):
                raise RuntimeError("Duplicate failed: " + asset["path"])
        asset_paths.append(asset["path"])
    for asset in plan["assets"]:
        for kind in ("bp", "bt"):
            path = asset[kind]
            if not client.call(ASSETS, "exists", {"path": path}):
                if not client.call(ASSETS, "duplicate", {"path": asset[kind + "Source"], "new_path": path}):
                    raise RuntimeError("Duplicate failed: " + path)
            asset_paths.append(path)
    for change in plan["assetProperties"]:
        ref = {"refPath": change["path"]}
        schema = json.loads(client.call(OBJECTS, "list_properties", {"instance": ref}))
        if any(key not in schema for key in change["values"]):
            raise RuntimeError("Property schema mismatch: " + change["path"])
        if not client.call(OBJECTS, "set_properties", {"instance": ref, "values": json.dumps(change["values"])}):
            raise RuntimeError("Property update failed: " + change["path"])
    compile_results = {}
    for asset in plan["assets"]:
        result = client.call(BLUEPRINTS, "compile_blueprint", {"blueprint": asset_ref(asset["bp"]), "warnings_as_errors": True})
        compile_results[asset["bp"]] = result
        print(json.dumps({"compile": asset["bp"], "result": result}), flush=True)
    for change in plan["assetProperties"]:
        actual = json.loads(client.call(OBJECTS, "get_properties", {
            "instance": {"refPath": change["path"]}, "properties": list(change["values"])}))
        verify_subset(actual, change["values"], change["path"])
    save(client, asset_paths)

    registered_tags = client.call(TAGS, "ListTags", {"parentTag": "GASData.CoolDown"})
    for skill in plan["skills"].values():
        tag = skill["coolDownTags"]["TagName"]
        if tag not in registered_tags:
            client.call(TAGS, "AddTag", {"tagName": tag, "tagSource": "", "comment": "Monster skill cooldown"})

    after = {}
    after[table_names[0]] = write_table(client, table_names[0], plan["skills"], before[table_names[0]])
    monsters = copy.deepcopy(plan["monsters"])
    for monster in monsters.values():
        # Native DataTableTools reserves Name for row keys. Display labels are
        # retained in pack.json; do not overwrite row keys with the FText Name.
        monster.pop("name", None)
    after[table_names[1]] = write_table(client, table_names[1], monsters, before[table_names[1]])
    groups = {}
    new_ids = {row["monsterId"] for row in monsters.values()}
    for key, values in plan["spawnGroupAdditions"].items():
        current = copy.deepcopy(before[table_names[2]][key]["monsterSpawnInfos"])
        for entry in values["monsterSpawnInfos"]:
            if entry["MonsterID"] in new_ids and not any(row["MonsterID"] == entry["MonsterID"] for row in current):
                current.append(entry)
        groups[key] = {"monsterSpawnInfos": current}
    after[table_names[2]] = write_table(client, table_names[2], groups, before[table_names[2]])
    write_json("tables-after.json", after)
    write_json("registration-result.json", {"saved_assets": asset_paths, "saved_tables": list(after),
        "monster_ids": sorted(new_ids), "skill_ids": [row["skillId"] for row in plan["skills"].values()],
        "existing_rows_preserved": True, "blueprint_compiles": compile_results})
    print("Monster registration and readback completed.", flush=True)


if __name__ == "__main__":
    main()
